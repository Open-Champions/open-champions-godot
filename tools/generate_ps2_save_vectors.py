#!/usr/bin/env python3
"""Regenerate the PS2 memory-card save vectors from the hash-pinned research reader.

The research repository's tools/ref_save.py, tools/test_ref_save.py and
tools/difftest_save.py are imported read-only. Every scenario is synthetic: the
records, cameras and grids are the ones those files build. No executable, disc
or memory-card file is read. The difftest scenarios are the model side of the
26 properties it compared with the original functions. Output is checked in.

  python3 tools/generate_ps2_save_vectors.py --research ../../../champions-re-wt/research-saves
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import sys

root = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--research', type=Path, required=True)
p.add_argument('--output', type=Path, default=root / 'native/tests/ps2_save_vectors.inc')
a = p.parse_args()
pin = json.loads((root / 'native/tests/ps2_save_contract.json').read_text())
for rel, expected in pin['sha256'].items():
    if hashlib.sha256((a.research / rel).read_bytes()).hexdigest() != expected:
        raise SystemExit('Contract hash mismatch: ' + rel)
sys.dont_write_bytecode = True
import dis  # noqa: E402,F401  (tools/dis.py shadows the stdlib module; load the real one first)
tools = a.research / 'tools'
sys.path.insert(0, str(tools))


def load(name):
    spec = importlib.util.spec_from_file_location(name, tools / (name + '.py'))
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


S = load('ref_save')
T = load('test_ref_save')
D = load('difftest_save')


def fnv(data):
    h = 0xCBF29CE484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def lcg_bytes(seed, size):
    """The deterministic filler shared with ps2_save_tests.cpp."""
    x = seed & 0xFFFFFFFF
    out = bytearray(size)
    for i in range(size):
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        out[i] = (x >> 16) & 0xFF
    return bytes(out)


out = ['// Generated by tools/generate_ps2_save_vectors.py from t3/research-saves %s. Do not edit.' % pin['commit'][:7],
       '// Each row: scenario name, byte length, FNV-1a 64 of the bytes ref_save produced.']
rows = []


def image(name, data):
    rows.append('{"%s", %du, 0x%016xull},' % (name, len(data), fnv(data)))


# tools/test_ref_save.py scenarios.
image('ref.crypt', S.build_slot(T._inputs()))
second = S.LiveCharacter(T._record(name=b'Bram', live_base=0x4D8AF0 + S.RECORD_SIZE, object_addr=0x01100200),
                         0x4D8AF0 + S.RECORD_SIZE, facing=9, position=(4.0, 5.0, 6.0))
first = T._inputs().players[0]
image('ref.one_player', S.build_slot(T._inputs(num_players=2, one_player=True, players=(first, second), memcard_state=4)))
image('ref.hub', S.build_slot(T._inputs(level_name='hub', subname='west', acts=((('town', 0x1800), ('hub', 0x1000)),))))
previous = bytearray(S.FILE_SIZE)
previous[13:0x14] = b'\x11' * 7
image('ref.game_complete', S.build_slot(T._inputs(game_complete=True, previous=bytes(previous))))
previous = bytearray(S.FILE_SIZE)
previous[S.DATA_AT:S.DATA_AT + 4] = b'\x22\x22\x22\x22'
S._write_cstr(previous, S.DIRECTORY_AT, 'old', 0x14)
struct.pack_into('<I', previous, S.DIRECTORY_AT + 0x14, 0x40000)
image('ref.does_not_fit', S.build_slot(T._inputs(previous=bytes(previous))))
bare = S.LiveCharacter(T._record(object_addr=0), 0x4D8AF0, facing=1, position=(9, 9, 9))
other = S.LiveCharacter(T._record(name=b'Bram', live_base=0x4D8AF0 + S.RECORD_SIZE, object_addr=0x01100200),
                        0x4D8AF0 + S.RECORD_SIZE, facing=0x2222, position=(8.0, 7.0, 6.0))
image('ref.pose_fallback', S.build_slot(T._inputs(memcard_state=4, num_players=2, players=(bare, other), alive_first=-1)))
image('ref.set_count', S.set_player_count(S.build_slot(T._inputs(num_players=2, one_player=True, memcard_state=4,
                                                                  players=T._inputs().players * 2)), 1))
base = 0x4D8AF0
saved = S.encode_saved_record(T._record(live_base=base), base)
image('ref.saved_record', saved)
image('ref.loaded_record', S.decode_loaded_record(saved, base))

# tools/difftest_save.py: the model side of every image the original matched.
grid = bytearray(S.AUTOMAP_GRID_SPAN)
grid[1] = 0xF0
grid[5] = 0x17
grid[0x361] = 0x80


def common(**kwargs):
    return D._common(**kwargs)[0]


image('diff.build.crypt', S.build_slot(common(quests=(('opened', 7), ('door', -2)), grid=bytes(grid), players=2)))
image('diff.build.unknown_level', S.build_slot(common(level='nope', previous=bytes([0x5A]) * S.FILE_SIZE)))
image('diff.build.tail_left_in_place', S.build_slot(common(card=4, previous=bytes([0x11]) * S.FILE_SIZE,
                                                           quests=(('opened', 7),))))
previous = bytearray(S.FILE_SIZE)
previous[13:0x14] = b'\x11' * 7
image('diff.build.game_complete', S.build_slot(common(complete=True, previous=bytes(previous))))
image('diff.build.one_player', S.build_slot(common(players=2, one=True, card=4)))
image('diff.build.card_busy', S.build_slot(common(card=4)))
image('diff.build.flag_blocks_store', S.build_slot(common(flag=0x800)))
previous = bytearray(S.FILE_SIZE)
previous[S.DATA_AT:S.DATA_AT + 4] = b'\x22\x22\x22\x22'
S._write_cstr(previous, S.DIRECTORY_AT, 'old', 0x14)
struct.pack_into('<I', previous, S.DIRECTORY_AT + 0x14, 0x40000)
image('diff.build.level_does_not_fit', S.build_slot(common(previous=bytes(previous))))
bare_base, other_base = D.G_PLAYERS, D.G_PLAYERS + S.RECORD_SIZE
bare = S.LiveCharacter(D.make_record('Aria', 777, bare_base, 0), bare_base, facing=1, position=(9, 9, 9))
other = S.LiveCharacter(D.make_record('Bram', 50, other_base, D.OBJ_BASE + 0x200), other_base,
                        facing=0x2222, position=(8.0, 7.0, 6.0))
camera = D.camera_parts()[3]
image('diff.build.pose_fallback', S.build_slot(S.SlotInputs(
    level_name='crypt', acts=((('crypt', 0x2000),),), num_players=2, players=(bare, other), alive_first=-1,
    camera=camera, jump_count=0, jump_dest=bytes(S.JUMP_DEST_SIZE), play_time=1, difficulty=1, save_arg=1,
    memcard_state=4)))
image('diff.build.hub_row0', S.build_slot(common(level='hub', sub='west', acts=((('town', 0x1800), ('hub', 0x1000)),))))
image('diff.count.both_fields', S.set_player_count(S.build_slot(common(players=2, one=True, card=4)), 1))
image('diff.load.record', S.decode_loaded_record(
    S.build_slot(common(quests=(('opened', 7), ('door', -2)), players=2, grid=b'\x00' * 8))[
        S.PLAYERS_AT + S.POSE_SIZE:S.PLAYERS_AT + S.BLOCK_SIZE], D.G_PLAYERS))
image('diff.camera', camera)

# Automap: the test grid, and an LCG-filled grid.
pattern = bytearray(S.AUTOMAP_GRID_SPAN)
for offset, value in ((1, 0xF0), (5, 0x07), (9, 0x10), (13, 0xA0), (0x361, 0x20), (0x365, 0x30)):
    pattern[offset] = value
image('automap.pattern', S.pack_automap(bytes(pattern)))
image('automap.lcg', S.pack_automap(lcg_bytes(0x16865C, S.AUTOMAP_GRID_SPAN)))
image('automap.short', S.pack_automap(lcg_bytes(7, 0x400)))

# Options: both schemes, and the single dirty row the original matched.
image('config.scheme1', S.config_set_defaults(-1, 1))
image('config.scheme0', S.config_set_defaults(-1, 0))
image('config.one_row', S.config_set_defaults(1, 2, bytes([0xAB]) * S.CONFIG_SIZE))
image('config.scheme2_kept', S.config_set_defaults(-1, 2, lcg_bytes(0x2F8, S.CONFIG_SIZE)))

out.append('const ImageVector IMAGE_VECTORS[] = {')
out.extend(rows)
out.append('};')

# player_checksum: the zero record, the difftest character live and saved, and LCG records.
checks = []
zero = bytes(S.RECORD_SIZE)
checks.append('{"zero", 0, 0x0u, 0u, 0x%08xu},' % S.player_checksum(0, 0, zero))
live = D.make_record('Aria', 777, D.G_PLAYERS, D.OBJ_BASE)
checks.append('{"diff.live", 0, 0x%xu, 0u, 0x%08xu},' % (D.G_PLAYERS, S.player_checksum(0, D.G_PLAYERS, live)))
saved_live = S.encode_saved_record(live, D.G_PLAYERS)
checks.append('{"diff.saved", 0, 0x%xu, 0u, 0x%08xu},' % (D.G_SAVED, S.player_checksum(0, D.G_SAVED, saved_live)))
for index in range(12):
    record = lcg_bytes(20973 + index, S.RECORD_SIZE)
    address = 0x1400000 + index * 0x5000
    for slot in range(4):
        checks.append('{"lcg", %d, 0x%xu, %du, 0x%08xu},' % (slot, address, 20973 + index,
                                                             S.player_checksum(slot, address, record)))
out.append('const ChecksumVector CHECKSUM_VECTORS[] = {')
out.extend(checks)
out.append('};')
a.output.write_text('\n'.join(out) + '\n')
print('%d image vectors, %d checksum vectors -> %s' % (len(rows), len(checks), a.output))
