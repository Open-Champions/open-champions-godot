#!/usr/bin/env python3
"""Generate native/src/creature_class_table.inc: which factory rows build a Creature.

Source: research t3/research-items-gaps ecf9742, docs/spec/hide-monster.md sections 3-4.
hideMonster / showMonster test object flag 0x20 and write +0x231 only for objects that
have it; the only certain setter is Creature_ctor 0x109d68, so the answer is a property of
the factory row. tools/objects_census.py probe_class() decides it by running the original
world_objectFactory and the constructor chain in tools/ee_emu.py against the owner's own
executable (the rule is quoted in that file's docstring).

For every name-test row of native/src/level_factory_table.inc that builds an object, this
tool picks a class name that reaches that row first (the order and the case-insensitive
equal/prefix tests are the factory's), probes it, and cross-checks the probe's pool size
and constructor against the row. A row where anything disagrees, or where the probe does
not decide, is written as unknown (kind 2) and stays refused natively.

The output holds only the addresses of the rows' test strings and one digit. No name,
byte or string of the executable is written.

  python3 tools/generate_creature_class_table.py \
      --research-dir <research-checkouts>/research-items-gaps \
      --elf <research-checkouts>/research-items-gaps/local/elf/SLUS_209.73 \
      --out native/src/creature_class_table.inc --contract native/tests/creature_class_contract.json
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

COMMIT = "ecf9742"
FILES = (
    "docs/spec/hide-monster.md",
    "docs/spec/items-gaps.md",
    "tools/objects_census.py",
    "tools/ref_hide_monster.py",
    "tools/ee_emu.py",
)
ROW = re.compile(r"\{(true|false), (0x[0-9a-f]+), (0x[0-9a-f]+), \{(0x[0-9a-f]+), (0x[0-9a-f]+)\}, (\d), (true|false)\}")


def read_rows(path):
    out = []
    for line in path.read_text().splitlines():
        m = ROW.match(line.strip())
        if m:
            count = int(m.group(6))
            out.append(dict(prefix=m.group(1) == "true", name=int(m.group(2), 16), size=int(m.group(3), 16),
                            calls=[int(m.group(4), 16), int(m.group(5), 16)][:count],
                            clear=m.group(7) == "true"))
    return out


def first_match(table, name):
    low = name.lower()
    for index, row in enumerate(table):
        text = row["text"].lower()
        if row["prefix"]:
            if low.startswith(text):
                return index
        elif low == text:
            return index
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--research-dir", required=True)
    ap.add_argument("--elf", required=True)
    ap.add_argument("--table", default="native/src/level_factory_table.inc")
    ap.add_argument("--out", required=True)
    ap.add_argument("--contract", required=True)
    args = ap.parse_args()
    research = Path(args.research_dir)
    head = subprocess.run(["git", "-C", str(research), "rev-parse", "--short", "HEAD"], capture_output=True,
                          text=True, check=True).stdout.strip()
    if head != COMMIT:
        sys.exit("research HEAD is %s, not %s" % (head, COMMIT))
    sys.path.append(str(research / "tools"))
    import dis  # noqa: F401,E402  (tools/dis.py shadows the standard library)
    import objects_census as OC  # noqa: E402
    from ee_emu import EE  # noqa: E402
    reader = EE(args.elf)
    table = read_rows(Path(args.table))
    for row in table:
        row["text"] = reader.mem.cstr(row["name"])
    lines, counts = [], {"creature": 0, "non-creature": 0, "unknown": 0, "skipped": 0}
    for index, row in enumerate(table):
        if row["size"] == 0 or row["clear"]:
            counts["skipped"] += 1
            continue
        candidates = [row["text"]] + ([row["text"] + "Q"] if row["prefix"] else [])
        name = next((c for c in candidates if first_match(table, c) == index), None)
        kind = 2
        if name is not None:
            size, ctor, result = OC.probe_class(args.elf, name.encode("latin-1"))
            agree = size == row["size"] and ctor in row["calls"]
            if agree and result == "creature":
                kind = 1
            elif agree and result == "non-creature":
                kind = 0
        counts[{1: "creature", 0: "non-creature", 2: "unknown"}[kind]] += 1
        lines.append("{0x%06x, %d}," % (row["name"], kind))
    Path(args.out).write_text(
        "// Generated by tools/generate_creature_class_table.py from research\n"
        "// t3/research-items-gaps %s (docs/spec/hide-monster.md 3-4). Do not edit.\n"
        "// {address of the factory row's test string, kind}: 1 the constructor chain reaches\n"
        "// Creature_ctor 0x109d68, 0 it reaches GameObject_ctor first, 2 not decided.\n" % COMMIT
        + "\n".join(lines) + "\n")
    contract = {"research_commit": COMMIT, "policy": "rta-creature-class-v1",
                "files": {f: hashlib.sha256((research / f).read_bytes()).hexdigest() for f in FILES},
                "rows": len(lines), "counts": counts}
    Path(args.contract).write_text(json.dumps(contract, indent=2) + "\n")
    print(json.dumps(counts))


if __name__ == "__main__":
    main()
