#!/usr/bin/env python3
"""givePlayerRandom vectors from the research reference model.

Reads tools/ref_item_drops.py (RandomGiver, the Ground item) from
t3/research-items-gaps at ecf9742 (docs/spec/item-drops.md section 2) and reuses
the authored synthetic world of tools/generate_script_items_vectors.py: made-up
definitions, names and strings, plus authored prefix and suffix rows so the item
generator can finish. No disc and no executable. Output is in that generator's
case format; native/tests/script_items_tests.cpp runs the kind givePlayerRandom
with the real item service (the ground item is built, not delegated).

  python3 tools/generate_give_random_vectors.py --research-dir DIR \
      --out native/tests/vectors/give_random.txt --contract native/tests/give_random_contract.json
"""
import argparse
import hashlib
import json
import random
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import generate_script_items_vectors as G  # noqa: E402

COMMIT = "ecf9742"
FILES = ("docs/spec/item-drops.md", "docs/spec/items-gaps.md", "tools/ref_item_drops.py",
         "tools/difftest_item_drops.py", "tools/ref_script_items.py", "tools/ref_items.py",
         "tools/ref_messages.py", "tools/ref_natives.py", "tools/ref_core.py")
SEED = 20973
G_LEVEL_NAME, S_FRAGMENT = 0x41B721, 0x5312A8
SPECIAL_TEXTS = {1: 0x5312B8, 2: 0x531308, 3: 0x531358}
G_PVP_A, G_PVP_B, G_LEVEL = 0x4F711C, 0x4F7120, 0x4F714C
PREFIX_AT, SUFFIX_AT = 0x400E50, 0x4019E0
POOL_BLOCK = 0x01F00000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--research-dir", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--contract", type=Path, required=True)
    ap.add_argument("--cases", type=int, default=120)
    args = ap.parse_args()
    root = args.research_dir.resolve()
    head = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"], capture_output=True,
                          text=True, check=True).stdout.strip()
    if head != COMMIT:
        sys.exit("research HEAD is %s, not %s" % (head, COMMIT))
    C, I, MB, N, R = G.load(root)
    sys.path.append(str(root / "tools"))
    import ref_item_drops as D  # noqa: E402
    img, defs, presets = G.build_image(N, I)
    # authored prefix and suffix rows (key pointer, level)
    for k in range(3):
        key = G.NAME_AREA + 0x4000 + 0x10 * k
        img.write(key, b"pre%d\0" % k)
        img.w32(PREFIX_AT + 0x28 * k, key)
        img.w16(PREFIX_AT + 0x28 * k + 4, 1 + k)
        skey = G.NAME_AREA + 0x4100 + 0x10 * k
        img.write(skey, b"suf%d\0" % k)
        img.w32(SUFFIX_AT + 0x14 * k, skey)
        img.w16(SUFFIX_AT + 0x14 * k + 4, 1 + k)
    for k in range(7):                           # weapon value multipliers, subtypes 0-6 (authored)
        img.w32(I.A_WEAPON_MULT + 4 * k, I.f_bits(1.0 + 0.25 * k))
    for row in range(12):                        # loot quality rows (authored)
        for i in range(3):
            img.w32(I.A_QUALITY + 12 * row + 4 * i, I.f_bits(0.5 + 0.1 * row + 0.05 * i))
    tables = I.Tables(G.fake_exe(I, img))
    rng = random.Random(SEED)
    out = G.Out()
    out.emit("# generated by tools/generate_give_random_vectors.py from research-items-gaps", COMMIT)
    for start, data in G.runs(img, set(a for a, s in img.writes for a in range(a, a + s))):
        out.emit("image", "%x" % start, G.hx(data))
    outcomes = {"ok": 0, "fault": 0, "drop": 0, "special": 0}
    for number in range(1, args.cases + 1):
        w = G.World(rng, R, I, N, img, defs, presets)
        w.plant()
        mem = w.mem
        mem.w32(0x4F719C, rng.choice([1, 1, 2, 3, 4, 5]))
        mem.write(S_FRAGMENT, b"zspecial\0")
        names = w.names()
        for d, text in SPECIAL_TEXTS.items():
            mem.write(text, rng.choice(names[:-1]) + b"\0")
        special = rng.random() < 0.35
        mem.write(G_LEVEL_NAME, (b"lvl_zspecial_2" if special else b"lvl_plain") + b"\0")
        mem.w32(G_PVP_A, rng.choice([0, 0, 1]))
        mem.w32(G_PVP_B, rng.choice([0, 0, 1]))
        mem.w32(G_LEVEL, I.f_bits(rng.choice([1.0, 3.0, 5.0, 8.0, 20.0])))
        if rng.random() < 0.5:                   # loads that make the drop path likely
            for slot in range(4):
                mem.w32(R.rec(slot) + R.P_LOAD_LIMIT, I.f_bits(rng.choice([0.0, 1.0, 5.0, 171.0])))
        before = G.snapshot(N, mem)
        mem.writes = []
        pool = rng.choice([0, POOL_BLOCK])
        answers = {"pool_new": pool, "net_isLocalSlot": rng.choice([0, 1]),
                   "skill_lightQuiverComplement": I.f_bits(0.9), "skill_axeBandolierComplement": I.f_bits(0.5),
                   "vars_get": 0, "text_lookup": 0x01500000}

        class DropHost(R.Host):
            def call(self, name, *a):
                if name in D.EXTERNALS:                 # the ground item's leaf call-outs: not logged
                    return (0, 0, 0, 0, 0, 0) if name == "model_getBounds" else 0
                return R.Host.call(self, name, *a)
        host = DropHost({k: (lambda *a, _v=v: _v) for k, v in answers.items()})
        giver = D.RandomGiver(mem, tables, host, G.SCRATCH)
        fault = None
        try:
            giver.givePlayerRandom()
        except (D.Fault, R.Fault, G.I_Fault(I), ValueError) as error:
            fault = str(error)
        out.emit("case", number, "givePlayerRandom")
        G.emit_world(out, w, before)
        for k, v in answers.items():
            out.emit("answer", k, v)
        out.emit("call", "givePlayerRandom")
        if fault is not None:
            out.emit("expect_fault")
            outcomes["fault"] += 1
        else:
            out.emit("expect_result", 0)
            for call, cargs in host.log:
                flat = []
                for a in cargs:
                    if isinstance(a, tuple):
                        flat += ["%x" % (x & 0xFFFFFFFF) for x in a]
                    else:
                        flat.append("%x" % (a & 0xFFFFFFFF))
                out.emit("expect_log", call, *flat)
            for start, data in G.runs(mem, G.written(mem, skip=((G.SCRATCH, G.SCRATCH + 0x48),))):
                out.emit("expect_bytes", "%x" % start, G.hx(data))
            outcomes["ok"] += 1
            outcomes["drop"] += sum(1 for o in giver.outcomes if o[2] == "drop")
            outcomes["special"] += sum(1 for o in giver.outcomes if o[0] == "special")
        out.emit("end")
    args.out.write_text("\n".join(out.lines) + "\n")
    contract = {"research_commit": COMMIT, "policy": "rta-give-random-v1", "seed": SEED, "cases": args.cases,
                "outcomes": outcomes, "files": {f: hashlib.sha256((root / f).read_bytes()).hexdigest() for f in FILES}}
    args.contract.write_text(json.dumps(contract, indent=2) + "\n")
    print(outcomes)


if __name__ == "__main__":
    main()
